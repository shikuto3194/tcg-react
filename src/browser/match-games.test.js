import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

for (const width of [1280, 390]) test(`multiple decks, match games, analysis and backup (${width}px)`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 900 });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const button = name => page.getByRole('button', { name, exact: true });
  const dialog = page.getByRole('dialog');
  const backup = { format: 'tcg-local-library-v1', activeGameId: 'multi', games: [{ gameId: 'multi', name: '複数デッキ確認', cards: [{ id: 1, name: 'カードA', image: '' }, { id: 2, name: 'カードB', image: '' }], settings: { labels: ['項目1'], source: 'folder', sideDecks: [{ id: 's', name: 'サイド' }] }, storage: { savedCanvasDecks: JSON.stringify([{ id: 'a', name: '構築A', cards: [{ id: 1, count: 2 }], sideDecks: { s: [{ id: 2, count: 1 }] } }, { id: 'b', name: '構築B', cards: [{ id: 2, count: 3 }] }]) } }] };
  const importBackup = async bytes => {
    await button('設定').click(); await dialog.getByRole('button', { name: 'バックアップ', exact: true }).click();
    await dialog.locator('div:not([hidden]) > section input[type=file]').setInputFiles({ name: 'multi.json', mimeType: 'application/json', buffer: bytes });
    await expect(dialog).toHaveCount(0);
  };
  await importBackup(Buffer.from(JSON.stringify(backup)));
  await page.getByRole('combobox', { name: 'ゲーム', exact: true }).selectOption({ label: '複数デッキ確認（復元）' });
  await button('戦績を記録').click();
  await dialog.getByLabel('イベント名', { exact: true }).fill('2デッキBO3');
  await dialog.getByLabel('対戦形式', { exact: true }).fill('BO3');
  await dialog.getByLabel('使用するデッキ数', { exact: true }).fill('2');
  await dialog.getByRole('combobox', { name: 'デッキを登録', exact: true }).selectOption({ label: '構築A' });
  await dialog.getByRole('combobox', { name: 'デッキを登録', exact: true }).selectOption({ label: '構築B' });
  await expect(dialog.locator('.match-registered-deck')).toHaveCount(2);
  await dialog.locator('.match-event-decks').scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('registered-decks.png') });
  await dialog.getByRole('button', { name: '対戦を入力', exact: true }).click();
  await expect(dialog.locator('.match-round-context')).toContainText('BO3 · 2デッキ制');
  await dialog.getByRole('group', { name: 'マッチの結果', exact: true }).getByRole('radio', { name: '勝ち', exact: true }).check();
  for (const [index, [deck, opponent, result, turn]] of [['構築A', '相手X', '負け', 'first'], ['構築B', '相手Y', '勝ち', 'second'], ['構築A', '相手Y', '勝ち', 'second']].entries()) {
    await dialog.getByRole('button', { name: 'ゲームを追加', exact: true }).click();
    const game = dialog.locator('.match-game').nth(index);
    await game.getByRole('combobox', { name: '使用デッキ', exact: true }).selectOption(deck);
    await game.getByLabel('相手のデッキ', { exact: true }).fill(opponent);
    await game.getByRole('radio', { name: result, exact: true }).check();
    await game.getByRole('combobox', { name: '先攻・後攻', exact: true }).selectOption(turn);
    await game.getByRole('textbox', { name: 'メモ', exact: true }).fill(`ゲーム${index + 1}のメモ`);
  }
  const first = dialog.locator('.match-game').first();
  await first.locator('.match-snapshot > summary').click();
  await expect(first.locator('.match-snapshot')).toContainText('カードA2枚');
  await expect(first.locator('.match-snapshot')).toContainText('カードB1枚');
  await first.scrollIntoViewIfNeeded();
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('game-details.png') });
  // Deleting one game must preserve the other games and support cancelling.
  await dialog.getByRole('button', { name: 'ゲームを追加', exact: true }).click();
  const fourth = dialog.locator('.match-game').nth(3);
  await fourth.getByRole('button', { name: '第4ゲームを削除', exact: true }).click();
  await fourth.getByRole('button', { name: 'キャンセル', exact: true }).click();
  await fourth.getByRole('button', { name: '第4ゲームを削除', exact: true }).click();
  await fourth.getByRole('button', { name: '削除する', exact: true }).click();
  await expect(dialog.locator('.match-game')).toHaveCount(3);
  await dialog.getByRole('button', { name: '記録', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.match-recent')).toContainText('構築A / 構築B');
  await expect(page.locator('.match-summaries')).toContainText('1勝 0敗 0分');
  await page.locator('.match-recent').getByRole('button', { name: '詳細', exact: true }).click();
  await expect(dialog.getByLabel('使用するデッキ数', { exact: true })).toHaveValue('2');
  await expect(dialog.getByLabel('対戦形式', { exact: true })).toHaveValue('BO3');
  await expect(dialog.locator('.match-registered-deck')).toHaveCount(2);
  await dialog.getByRole('button', { name: '2. 対戦', exact: true }).click();
  await expect(dialog.locator('.match-game')).toHaveCount(3);
  await expect(first.getByRole('textbox', { name: 'メモ', exact: true })).toHaveValue('ゲーム1のメモ');
  await dialog.getByRole('button', { name: '閉じる', exact: true }).click();
  await button('分析').click();
  const summary = page.locator('.match-analysis-summary');
  await expect(summary).toContainText('1マッチ'); await expect(summary).toContainText('1勝 0敗 0分');
  await page.locator('.match-filter-heading button').first().click();
  const filters = page.locator('#analysis-filters');
  await filters.getByRole('combobox', { name: '集計', exact: true }).selectOption('deck');
  await expect(page.locator('.match-table tbody')).toContainText('構築A / 構築B');
  await filters.getByRole('combobox', { name: '集計単位', exact: true }).selectOption('game');
  await filters.getByRole('combobox', { name: '使用するデッキ数', exact: true }).selectOption('2');
  await expect(summary).toContainText('3ゲーム'); await expect(summary).toContainText('2勝 1敗 0分');
  await filters.getByRole('combobox', { name: '使用デッキ', exact: true }).selectOption('構築A');
  await filters.getByRole('combobox', { name: '先攻・後攻', exact: true }).selectOption('first');
  await expect(summary).toContainText('1ゲーム'); await expect(summary).toContainText('0勝 1敗 0分');
  await expect(page.locator('.match-chart:visible circle')).toHaveAttribute('cy', '150');
  await page.getByText('ゲームを見る（1件）', { exact: true }).click();
  await expect(page.locator('.match-event-history')).toContainText('ゲーム1のメモ');
  await page.screenshot({ path: testInfo.outputPath('game-analysis.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await button('設定').click(); await dialog.getByRole('button', { name: 'バックアップ', exact: true }).click();
  const download = page.waitForEvent('download'); await dialog.getByRole('button', { name: '画像込みバックアップ', exact: true }).click();
  const bytes = await readFile(await (await download).path());
  const exported = JSON.parse(bytes).games.find(game => game.name === '複数デッキ確認（復元）');
  expect(exported.events[0].matches[0].games).toHaveLength(3);
  expect(exported.events[0].decks).toHaveLength(2);
  expect(exported.events[0].matches[0].games[0].sideDecks.s[0].count).toBe(1);
  await dialog.locator('div:not([hidden]) > section input[type=file]').setInputFiles({ name: 'multi.json', mimeType: 'application/json', buffer: bytes });
  await expect(dialog).toHaveCount(0);
  await button('🏠').click();
  await page.getByRole('combobox', { name: 'ゲーム', exact: true }).selectOption({ label: '複数デッキ確認（復元）（復元）' });
  await page.reload();
  await page.locator('.match-recent').getByRole('button', { name: '詳細', exact: true }).click();
  await dialog.getByRole('button', { name: '2. 対戦', exact: true }).click();
  await expect(dialog.locator('.match-game')).toHaveCount(3);
  await expect(first.getByRole('combobox', { name: '使用デッキ', exact: true })).toHaveValue('構築A');
  await expect(first.getByRole('radio', { name: '負け', exact: true })).toBeChecked();
  expect(errors).toEqual([]);
});
