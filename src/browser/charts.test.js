import { test, expect } from '@playwright/test';
import { createEvent, createMatch } from '../analysis/model.js';

for (const width of [1280, 390]) test(`daily win rate and shared analysis period (${width}px)`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 900 });
  await page.clock.setFixedTime(new Date(2026, 9, 8, 12));
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const button = name => page.getByRole('button', { name, exact: true });
  const chart = page.locator('.match-chart:visible');
  await expect(chart.locator('circle')).toHaveCount(0);
  await expect(chart).toContainText('この期間に勝率を計算できる対戦はありません。');
  const events = [
    ['2025-12-30', ['win']], ['2026-08-02', ['loss']], ['2026-08-05', ['win', 'loss', 'draw']],
    ['2026-08-06', ['draw']], ['2026-08-07', ['']], ['2026-09-09', ['win']], ['2026-10-08', ['loss']], ['', ['win']],
  ].map(([at, results]) => ({ ...createEvent(), name: at || '日時不明', at, format: at === '2026-08-05' ? 'BO3' : 'BO1', matches: results.map((result, index) => ({ ...createMatch(), result, opponent: index ? 'Y' : 'X', deckName: index ? 'B' : 'A', turn: index ? 'second' : 'first' })) }));
  const backup = { format: 'tcg-local-library-v1', activeGameId: 'chart', games: [{ gameId: 'chart', name: '勝率確認', cards: [], settings: { labels: ['項目1'], source: 'folder' }, storage: {}, events }] };
  await button('設定').click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'バックアップ', exact: true }).click();
  await dialog.locator('div:not([hidden]) > section input[type=file]').setInputFiles({ name: 'chart.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await expect(dialog).toHaveCount(0);
  await page.getByRole('combobox', { name: 'ゲーム', exact: true }).selectOption({ label: '勝率確認（復元）' });
  await expect(chart).toContainText('2026/09/09〜2026/10/08');
  await expect(chart.locator('circle')).toHaveCount(2);
  await expect(chart.locator('circle[cy="25"]')).toHaveCount(1);
  await expect(chart.locator('circle[cy="150"]')).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath('home-win-rate.png'), fullPage: true });

  await button('分析').click();
  await expect(chart).toContainText('2025/12/30〜2026/10/08');
  await expect(chart.locator('circle')).toHaveCount(5);
  await expect(chart.locator('polyline')).toHaveAttribute('points', /\S+(?: \S+){4}/);
  await expect(page.getByRole('combobox', { name: '集計', exact: true })).toHaveCount(0);
  await expect(page.locator('.match-table tbody tr')).toHaveCount(1);
  await expect(page.locator('.match-table tbody')).toContainText('全体');
  await expect(page.locator('.match-table tbody')).toContainText('4／3／2');
  await expect(page.locator('.match-table tbody')).toContainText('57%');
  await page.getByRole('button', { name: width === 1280 ? 'フィルター' : 'フィルターを開く', exact: true }).click();
  const filters = page.locator('#analysis-filters');
  const grouping = filters.getByRole('combobox', { name: '集計', exact: true });
  await expect(grouping).toHaveValue('');
  await expect(grouping.locator('option:checked')).toHaveText('条件なし');
  const from = filters.getByLabel('開始日', { exact: true });
  const to = filters.getByLabel('終了日', { exact: true });
  await from.fill('2026-08-01'); await to.fill('2026-08-31');
  await expect(chart).toContainText('2026/08/01〜2026/08/31');
  await expect(chart.locator('circle')).toHaveCount(2);
  await expect(chart.locator('circle[cy="87.5"]')).toHaveCount(1);
  const fifty = chart.getByRole('button', { name: '2026/08/05：勝率 50%（1勝 1敗 1分）', exact: true });
  await fifty.click();
  await expect(chart.locator('[aria-live]')).toHaveText('2026/08/05：勝率 50%（1勝 1敗 1分）');
  const xs = await chart.locator('circle').evaluateAll(nodes => nodes.map(node => Number(node.getAttribute('cx'))));
  expect(xs[1] - xs[0]).toBeCloseTo(562 * 3 / 30, 5);
  await chart.getByRole('button', { name: '2026/08/06：勝率 —（0勝 0敗 1分）', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(chart.locator('[aria-live]')).toContainText('勝率 —');
  await fifty.focus(); await page.keyboard.press('Space');
  await expect(fifty).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.match-analysis-summary')).toContainText('1勝 2敗 2分');
  await expect(page.locator('.match-table tbody tr')).toHaveCount(1);
  await expect(page.locator('.match-table tbody')).toContainText('1／2／2');
  await expect(page.locator('.match-table tbody')).toContainText('33%');
  await expect(page.locator('.match-event-history')).toHaveCount(4);
  await page.screenshot({ path: testInfo.outputPath('analysis-win-rate.png'), fullPage: true });

  await filters.getByRole('combobox', { name: '相手のデッキ', exact: true }).selectOption('X');
  await expect(chart.locator('circle[cy="25"]')).toHaveCount(1);
  await expect(chart.locator('circle[cy="150"]')).toHaveCount(1);
  await filters.getByRole('combobox', { name: '相手のデッキ', exact: true }).selectOption('');
  await filters.getByRole('combobox', { name: '結果', exact: true }).selectOption('draw');
  await expect(chart.locator('circle')).toHaveCount(0);
  await expect(chart.locator('polyline')).toHaveAttribute('points', '');
  await filters.getByRole('combobox', { name: '結果', exact: true }).selectOption('unknown');
  await expect(chart.getByRole('button')).toHaveCount(0);
  await filters.getByRole('combobox', { name: '結果', exact: true }).selectOption('');
  await from.fill('2026-08-05'); await to.fill('2026-08-05');
  await expect(chart.locator('circle')).toHaveCount(1);
  await expect(chart.locator('circle')).toHaveAttribute('cx', '329');
  await to.fill('');
  await expect(chart).toContainText('2026/08/05〜2026/10/08');
  await expect(chart.locator('circle')).toHaveCount(3);
  await from.fill(''); await to.fill('2026-08-05');
  await expect(chart).toContainText('2025/12/30〜2026/08/05');
  await expect(chart.locator('circle')).toHaveCount(3);
  await from.fill('2026-08-06');
  await expect(page.getByRole('alert')).toContainText('終了日は開始日以降にしてください。');
  await expect(chart.locator('circle')).toHaveCount(0);
  await from.fill('2026-07-01'); await to.fill('2026-07-31');
  await expect(chart).toContainText('2026/07/01〜2026/07/31');
  await expect(chart.locator('[aria-live]')).toHaveText('この期間に勝率を計算できる対戦はありません。');
  await button(width === 1280 ? 'リセット' : '条件リセット').click();
  await expect(chart.locator('circle')).toHaveCount(5);
  await expect(chart).toContainText('2025/12/30〜2026/10/08');

  // Every shared condition must reach the summary, chart, table and event history.
  const select = (name, value) => filters.getByRole('combobox', { name, exact: true }).selectOption(value);
  const summary = page.locator('.match-analysis-summary');
  const table = page.locator('.match-table tbody');
  const history = page.locator('.match-event-history');
  const augustEvent = events.find(event => event.at === '2026-08-05');
  await grouping.selectOption('opponent');
  await expect(page.locator('.match-filter-status')).toHaveText('1条件を適用中');
  await button(width === 1280 ? '閉じる' : 'フィルターを閉じる').click();
  await expect(filters).toBeHidden();
  await expect(table.getByRole('row')).toHaveCount(2);
  await button(width === 1280 ? 'フィルター' : 'フィルターを開く').click();
  await expect(grouping).toHaveValue('opponent');
  await from.fill('2026-08-01'); await to.fill('2026-08-31');
  await select('イベント', augustEvent.id);
  await expect(summary).toContainText('1勝 1敗 1分');
  await expect(chart.locator('circle[cy="87.5"]')).toHaveCount(1);
  await expect(table.getByRole('row')).toHaveCount(2);
  await expect(history).toHaveCount(1);
  await expect(history).toContainText('2026-08-05');
  await select('イベント', ''); await select('対戦形式', 'BO3');
  await expect(summary).toContainText('1勝 1敗 1分');
  await expect(chart.locator('circle')).toHaveCount(1);
  await expect(table.getByRole('row')).toHaveCount(2);
  await expect(history).toHaveCount(1);
  await select('使用デッキ', 'A');
  await expect(summary).toContainText('1勝 0敗 0分');
  await expect(chart.locator('circle[cy="25"]')).toHaveCount(1);
  await expect(table.getByRole('row')).toHaveCount(1);
  await expect(history).toContainText('対戦を見る（1件）');
  await select('使用デッキ', ''); await select('先攻・後攻', 'second');
  await expect(summary).toContainText('0勝 1敗 1分');
  await expect(chart.locator('circle[cy="150"]')).toHaveCount(1);
  await expect(table.getByRole('row')).toHaveCount(1);
  await expect(table).toContainText('Y');
  await expect(history).toContainText('対戦を見る（2件）');
  await select('イベント', augustEvent.id); await select('使用デッキ', 'B');
  await select('相手のデッキ', 'Y'); await select('結果', 'loss');
  await expect(page.locator('.match-filter-status')).toHaveText('9条件を適用中');
  await expect(summary).toContainText('0勝 1敗 0分');
  await expect(chart.locator('circle')).toHaveCount(1);
  await expect(chart.locator('circle')).toHaveAttribute('cy', '150');
  await expect(table.getByRole('row')).toHaveCount(1);
  await expect(table).toContainText('0／1／0');
  await expect(history).toHaveCount(1);
  await expect(history).toContainText('対戦を見る（1件）');
  await history.getByText('対戦を見る（1件）', { exact: true }).click();
  await expect(history.locator('.match-history-row')).toHaveCount(1);
  await expect(history.locator('.match-history-row')).toContainText('後攻');
  await select('使用デッキ', 'A');
  await expect(summary).toContainText('0勝 0敗 0分');
  await expect(chart.locator('circle')).toHaveCount(0);
  await expect(table).toHaveCount(0);
  await expect(history).toHaveCount(0);
  await button(width === 1280 ? 'リセット' : '条件リセット').click();
  await expect(summary).toContainText('4勝 3敗 2分');
  await expect(chart.locator('circle')).toHaveCount(5);
  await expect(grouping).toHaveValue('');
  await expect(page.locator('.match-filter-status')).toHaveCount(0);
  await expect(table.getByRole('row')).toHaveCount(1);
  await expect(table).toContainText('全体');
  await expect(table).toContainText('4／3／2');
  await expect(history).toHaveCount(8);
  await page.screenshot({ path: testInfo.outputPath('analysis-no-group.png'), fullPage: true });
  await grouping.selectOption('deck');
  await expect(page.locator('.match-table thead')).toContainText('使用デッキ');
  await expect(table.getByRole('row')).toHaveCount(2);
  await grouping.selectOption('');
  await expect(table.getByRole('row')).toHaveCount(1);
  await expect(table).toContainText('全体');
  await expect(table).toContainText('4／3／2');
  await expect(summary).toContainText('4勝 3敗 2分');
  await expect(chart.locator('circle')).toHaveCount(5);
  await expect(history).toHaveCount(8);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
